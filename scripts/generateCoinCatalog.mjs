import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localCoinsDir = path.resolve(root, 'public/icons/coins');
const siblingCoinsDir = path.resolve(root, '../flowx/public/icons/coins');
const coinsDir = fs.existsSync(localCoinsDir)
  ? localCoinsDir
  : fs.existsSync(siblingCoinsDir)
    ? siblingCoinsDir
    : localCoinsDir;
const outFile = path.resolve(root, 'src/generated/coinCatalog.ts');

const FEATURED_COIN_IDS = ['btc', 'eth', 'sol', 'bnb', 'hype', 'xrp'];

function coinIdToLabel(coinId) {
  return `${coinId.toUpperCase()}USDT`;
}

function coinIdToValue(coinId) {
  return `asset-${coinId}`;
}

if (!fs.existsSync(coinsDir)) {
  if (fs.existsSync(outFile)) {
    console.log(`Skipping coin catalog generation — ${coinsDir} missing, using existing catalog`);
    process.exit(0);
  }

  throw new Error(`Coins directory not found: ${coinsDir}`);
}

const coinIds = fs
  .readdirSync(coinsDir)
  .filter((name) => name.endsWith('.webp'))
  .map((name) => name.slice(0, -'.webp'.length))
  .sort((a, b) => a.localeCompare(b));

const featuredSet = new Set(FEATURED_COIN_IDS);
const orderedCoinIds = [
  ...FEATURED_COIN_IDS.filter((id) => coinIds.includes(id)),
  ...coinIds.filter((id) => !featuredSet.has(id)),
];

const suggestions = orderedCoinIds.map((coinId) => ({
  value: coinIdToValue(coinId),
  label: coinIdToLabel(coinId),
  coinId,
  keywords: [coinId, coinIdToLabel(coinId)],
}));

const file = `/** Generated by scripts/generateCoinCatalog.mjs — do not edit. */
export const COIN_IDS: readonly string[] = ${JSON.stringify(orderedCoinIds)};

export type TerminalAssetSuggestion = {
  value: string;
  label: string;
  coinId: string;
  keywords?: string[];
};

export const TERMINAL_ASSET_SUGGESTIONS: readonly TerminalAssetSuggestion[] = ${JSON.stringify(suggestions)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, file);
console.log(`Wrote ${orderedCoinIds.length} coins to ${path.relative(root, outFile)}`);
